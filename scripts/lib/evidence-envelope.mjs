import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { isDeepStrictEqual } from 'node:util';

import { loadEvidenceEnvelopeContract } from './evidence-envelope-contract.mjs';
import { validateJsonSchema } from './json-schema-subset.mjs';

const CONTRACT = 'forge-evidence-envelope';
const SCHEMA_VERSION = 1;
const CONSTRUCTOR_OWNED_FIELDS = ['schema_version', 'contract', 'envelope_id', 'content_digest'];

function isPlainObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function compareText(left, right) {
  return left < right ? -1 : left > right ? 1 : 0;
}

function stableValue(value) {
  if (Array.isArray(value)) return value.map(stableValue);
  if (!isPlainObject(value)) return value;
  return Object.fromEntries(
    Object.keys(value)
      .sort(compareText)
      .map((key) => [key, stableValue(value[key])]),
  );
}

function sha256Buffer(value) {
  return `sha256:${crypto.createHash('sha256').update(value).digest('hex')}`;
}

function sha256Json(value) {
  return sha256Buffer(JSON.stringify(stableValue(value)));
}

function issue(pathname, code, message, details = {}) {
  return { path: pathname, code, message, ...details };
}

function stableIssues(issues) {
  const unique = new Map();
  for (const item of issues) {
    unique.set(`${item.path}\u0000${item.code}\u0000${item.message}`, item);
  }
  return [...unique.values()].sort(
    (left, right) =>
      left.path.localeCompare(right.path) ||
      left.code.localeCompare(right.code) ||
      left.message.localeCompare(right.message),
  );
}

export class EvidenceEnvelopeError extends Error {
  constructor(code, issues, options = {}) {
    const normalized = stableIssues(issues);
    super(
      normalized.length === 1
        ? normalized[0].message
        : `Evidence Envelope rejected (${normalized.length} issues)`,
      options,
    );
    this.name = 'EvidenceEnvelopeError';
    this.code = code;
    this.issues = normalized;
  }
}

function cloneInput(value) {
  try {
    return structuredClone(value);
  } catch (error) {
    throw new EvidenceEnvelopeError(
      'INVALID_ENVELOPE',
      [issue('', 'invalid_value', `envelope input cannot be cloned: ${error.message}`)],
      { cause: error },
    );
  }
}

function decodeInput(input) {
  if (typeof input !== 'string' && !Buffer.isBuffer(input)) return cloneInput(input);
  try {
    return JSON.parse(String(input));
  } catch (error) {
    throw new EvidenceEnvelopeError(
      'INVALID_JSON',
      [issue('', 'invalid_json', `envelope is not valid JSON: ${error.message}`)],
      { cause: error },
    );
  }
}

function loadSchema(rootDir) {
  try {
    return loadEvidenceEnvelopeContract(rootDir).schema;
  } catch (error) {
    throw new EvidenceEnvelopeError(
      'INVALID_CONTRACT',
      (error.issues ?? [error.message]).map((message) =>
        issue('', 'invalid_contract', String(message))),
      { cause: error },
    );
  }
}

function expectedContentDigest(envelope) {
  const content = { ...envelope };
  delete content.content_digest;
  return sha256Json(content);
}

function acceptEnvelope(input, options) {
  const envelope = decodeInput(input);
  const schema = loadSchema(options.rootDir);
  const issues = validateJsonSchema(envelope, schema);
  if (issues.length === 0 && envelope.content_digest !== expectedContentDigest(envelope)) {
    issues.push(
      issue(
        '/content_digest',
        'content_digest_mismatch',
        'envelope content digest does not match its canonical content',
      ),
    );
  }
  if (issues.length > 0) throw new EvidenceEnvelopeError('INVALID_ENVELOPE', issues);
  return envelope;
}

export function parseEvidenceEnvelope(input, options = {}) {
  return acceptEnvelope(input, { rootDir: process.cwd(), ...options });
}

export function createEvidenceEnvelope(input, options = {}) {
  const observed = cloneInput(input);
  if (!isPlainObject(observed)) {
    throw new EvidenceEnvelopeError(
      'INVALID_ENVELOPE',
      [issue('', 'type', 'constructor input must be an object')],
    );
  }
  const owned = CONSTRUCTOR_OWNED_FIELDS.filter((field) => Object.hasOwn(observed, field));
  if (owned.length > 0) {
    throw new EvidenceEnvelopeError(
      'INVALID_ENVELOPE',
      owned.map((field) =>
        issue(`/${field}`, 'constructor_owned', `${field} is generated by createEvidenceEnvelope`)),
    );
  }
  const envelope = {
    schema_version: SCHEMA_VERSION,
    contract: CONTRACT,
    envelope_id: `${observed.target?.result_ref ?? 'unbound'}.envelope`,
    ...observed,
  };
  envelope.content_digest = expectedContentDigest(envelope);
  return acceptEnvelope(envelope, { rootDir: process.cwd(), ...options });
}

function isSafeRetainedBasename(value) {
  return (
    typeof value === 'string' &&
    value !== '.' &&
    value !== '..' &&
    /^[A-Za-z0-9][A-Za-z0-9._-]{0,254}$/.test(value)
  );
}

function readRetainedFile(reference, evidenceRoot, label) {
  const issues = [];
  if (!isPlainObject(reference)) {
    throw new EvidenceEnvelopeError(
      'INVALID_REFERENCE',
      [issue('', 'invalid_reference', `${label} reference must be an object`)],
    );
  }
  if (!isSafeRetainedBasename(reference.ref)) {
    issues.push(issue('/ref', 'unsafe_locator', `${label} reference must be a basename`));
  }
  if (!/^sha256:[0-9a-f]{64}$/.test(reference.digest ?? '')) {
    issues.push(issue('/digest', 'invalid_reference', `${label} reference digest is invalid`));
  }
  if (!Number.isInteger(reference.bytes) || reference.bytes < 0) {
    issues.push(issue('/bytes', 'invalid_reference', `${label} reference byte count is invalid`));
  }
  if (issues.length > 0) throw new EvidenceEnvelopeError('INVALID_REFERENCE', issues);

  let canonicalRoot;
  let before;
  let retainedPath;
  let descriptor;
  try {
    canonicalRoot = fs.realpathSync(evidenceRoot);
    retainedPath = path.join(canonicalRoot, reference.ref);
    before = fs.lstatSync(retainedPath, { bigint: true });
    if (!before.isFile() || before.nlink !== 1n) {
      throw new EvidenceEnvelopeError(
        'INVALID_REFERENCE',
        [
          issue(
            '/ref',
            'retained_evidence_not_regular',
            `${label} must be one regular, non-linked retained file`,
          ),
        ],
      );
    }
    descriptor = fs.openSync(
      retainedPath,
      fs.constants.O_RDONLY | (fs.constants.O_NOFOLLOW ?? 0),
    );
  } catch (error) {
    if (error instanceof EvidenceEnvelopeError) throw error;
    throw new EvidenceEnvelopeError(
      'INVALID_REFERENCE',
      [issue('/ref', 'retained_evidence_missing', `${label} file is unavailable: ${error.message}`)],
      { cause: error },
    );
  }
  try {
    const opened = fs.fstatSync(descriptor, { bigint: true });
    if (
      !opened.isFile() ||
      opened.nlink !== 1n ||
      opened.dev !== before.dev ||
      opened.ino !== before.ino
    ) {
      throw new EvidenceEnvelopeError(
        'INVALID_REFERENCE',
        [issue('/ref', 'retained_identity_changed', `${label} file identity changed while opening`)],
      );
    }
    const bytes = fs.readFileSync(descriptor);
    const after = fs.fstatSync(descriptor, { bigint: true });
    const pathAfter = fs.lstatSync(retainedPath, { bigint: true });
    if (
      after.dev !== opened.dev ||
      after.ino !== opened.ino ||
      after.size !== opened.size ||
      pathAfter.dev !== opened.dev ||
      pathAfter.ino !== opened.ino ||
      pathAfter.nlink !== 1n
    ) {
      throw new EvidenceEnvelopeError(
        'INVALID_REFERENCE',
        [issue('/ref', 'retained_identity_changed', `${label} file changed while being read`)],
      );
    }
    if (Number(opened.size) !== reference.bytes || sha256Buffer(bytes) !== reference.digest) {
      throw new EvidenceEnvelopeError(
        'INVALID_REFERENCE',
        [issue('', 'retained_integrity_mismatch', `${label} file does not match its retained reference`)],
      );
    }
    return bytes;
  } finally {
    fs.closeSync(descriptor);
  }
}

function bindingIssue(pathname, code, message, expected, actual) {
  return issue(pathname, code, message, { expected, actual });
}

function bindingIssues(envelope, report, evidenceId) {
  const issues = [];
  if (!isPlainObject(report)) {
    return [issue('/report', 'invalid_context', 'binding context report must be an object')];
  }
  const evidence = report.evidence?.find((item) => item?.id === evidenceId);
  if (!evidence) {
    return [issue('/evidenceId', 'result_missing', 'binding context evidence does not exist')];
  }
  const event = report.events?.find((item) => item?.id === evidence.event_id);
  if (!event) {
    issues.push(issue('/action/event_id', 'action_mismatch', 'bound evidence event does not exist'));
  }
  const exactBindings = [
    ['/issuer_ref', 'issuer_mismatch', evidence.producer_ref, envelope.issuer_ref],
    ['/source_level', 'source_level_mismatch', evidence.source_kind, envelope.source_level],
    ['/target/report_id', 'target_mismatch', report.report_id, envelope.target.report_id],
    [
      '/target/comparison_group_id',
      'target_mismatch',
      report.experiment?.comparison_group_id,
      envelope.target.comparison_group_id,
    ],
    ['/target/arm_id', 'target_mismatch', report.experiment?.arm?.id, envelope.target.arm_id],
    [
      '/target/repeat_index',
      'target_mismatch',
      report.experiment?.reproduction?.repeat_index,
      envelope.target.repeat_index,
    ],
    [
      '/target/request_fingerprint',
      'target_mismatch',
      report.experiment?.reproduction?.request_fingerprint,
      envelope.target.request_fingerprint,
    ],
    [
      '/target/objective_ref',
      'target_mismatch',
      report.experiment?.objective?.id,
      envelope.target.objective_ref,
    ],
    [
      '/target/objective_digest',
      'target_mismatch',
      report.experiment?.objective?.digest,
      envelope.target.objective_digest,
    ],
    ['/target/result_ref', 'target_mismatch', evidence.id, envelope.target.result_ref],
    ['/action/event_id', 'action_mismatch', event?.id, envelope.action.event_id],
    ['/action/type', 'action_mismatch', event?.type, envelope.action.type],
    ['/action/actor', 'action_mismatch', event?.actor, envelope.action.actor],
    ['/action/status', 'action_mismatch', event?.status, envelope.action.status],
    ['/action/observed_at', 'action_mismatch', event?.observed_at, envelope.action.observed_at],
    ['/evidence/locator', 'payload_binding_mismatch', evidence.locator, envelope.evidence.locator],
    ['/evidence/digest', 'payload_binding_mismatch', evidence.digest, envelope.evidence.digest],
  ];
  for (const [pathname, code, expected, actual] of exactBindings) {
    if (!Object.is(expected, actual)) {
      issues.push(bindingIssue(pathname, code, `${pathname.slice(1)} does not match binding context`, expected, actual));
    }
  }
  if (evidence.envelope_ref === undefined || evidence.envelope_ref.length === 0) {
    issues.push(issue('/evidence/envelope_ref', 'envelope_reference_missing', 'report evidence has no envelope reference'));
  }
  if (!isDeepStrictEqual(report.experiment?.workspace, envelope.workspace)) {
    issues.push(
      bindingIssue(
        '/workspace',
        'workspace_mismatch',
        'envelope workspace does not match the report workspace version',
        report.experiment?.workspace,
        envelope.workspace,
      ),
    );
  }
  const issuedAt = Date.parse(envelope.issued_at);
  const observedAt = Date.parse(envelope.action.observed_at);
  const executionStart = Date.parse(report.execution?.started_at);
  const executionEnd = Date.parse(report.execution?.ended_at);
  if (
    !Number.isFinite(issuedAt) ||
    !Number.isFinite(observedAt) ||
    !Number.isFinite(executionStart) ||
    !Number.isFinite(executionEnd) ||
    issuedAt < observedAt ||
    issuedAt < executionStart ||
    issuedAt > executionEnd
  ) {
    issues.push(
      issue(
        '/issued_at',
        'time_binding_mismatch',
        'envelope issue time must follow the action and remain inside report execution',
      ),
    );
  }
  return issues;
}

export function verifyEvidenceEnvelope(reference, options = {}) {
  const rootDir = options.rootDir ?? process.cwd();
  const bytes = readRetainedFile(reference, options.evidenceRoot, 'envelope');
  const envelope = parseEvidenceEnvelope(bytes, { rootDir });
  const issues = bindingIssues(envelope, options.report, options.evidenceId);
  const expectedEnvelopeRef = `${envelope.content_digest.slice('sha256:'.length)}.evidence-envelope.json`;
  if (reference.ref !== expectedEnvelopeRef) {
    issues.push(
      issue(
        '/ref',
        'content_address_mismatch',
        'retained envelope filename does not match its canonical content digest',
      ),
    );
  }
  if (options.report?.evidence?.find((item) => item?.id === options.evidenceId)?.envelope_ref !== reference.ref) {
    issues.push(
      issue(
        '/ref',
        'envelope_reference_mismatch',
        'retained envelope reference does not match report evidence',
      ),
    );
  }
  if (issues.length > 0) throw new EvidenceEnvelopeError('INVALID_BINDING', issues);

  const payloadReference = {
    ref: envelope.evidence.locator,
    digest: envelope.evidence.digest,
    bytes: envelope.evidence.bytes,
  };
  let payloadBytes;
  try {
    payloadBytes = readRetainedFile(payloadReference, options.evidenceRoot, 'payload');
  } catch (error) {
    const unsafe = error.issues?.some((item) => item.code === 'unsafe_locator');
    const missing = error.issues?.some((item) =>
      item.code === 'retained_evidence_missing' || item.code === 'retained_evidence_not_regular');
    const integrity = error.issues?.some((item) => item.code === 'retained_integrity_mismatch');
    throw new EvidenceEnvelopeError(
      'INVALID_BINDING',
      [
        issue(
          unsafe || missing ? '/evidence/locator' : '/evidence/digest',
          unsafe
            ? 'unsafe_locator'
            : missing
              ? 'payload_missing'
              : integrity
                ? 'payload_integrity_mismatch'
                : 'payload_read_failed',
          unsafe
            ? 'payload locator is unsafe'
            : missing
              ? 'payload file is unavailable or not a retained regular file'
              : integrity
                ? 'payload file does not match envelope bytes and digest'
                : 'payload file could not be verified',
        ),
      ],
      { cause: error },
    );
  }
  if (envelope.evidence.kind === 'command') {
    let command;
    try {
      command = JSON.parse(String(payloadBytes));
    } catch (error) {
      throw new EvidenceEnvelopeError(
        'INVALID_BINDING',
        [issue('/evidence/result', 'command_receipt_invalid', 'command evidence payload is not valid JSON')],
        { cause: error },
      );
    }
    const expected = {
      exit_code: command?.exit_code,
      termination: command?.termination,
      stdout_digest: command?.stdout?.observed_digest,
      stderr_digest: command?.stderr?.observed_digest,
    };
    if (!isDeepStrictEqual(envelope.evidence.result, expected)) {
      throw new EvidenceEnvelopeError(
        'INVALID_BINDING',
        [
          issue(
            '/evidence/result',
            'command_summary_mismatch',
            'command result summary does not match the retained command receipt',
          ),
        ],
      );
    }
  } else if (
    envelope.evidence.kind === 'artifact' &&
    envelope.evidence.result.artifact_digest !== envelope.evidence.digest
  ) {
    throw new EvidenceEnvelopeError(
      'INVALID_BINDING',
      [
        issue(
          '/evidence/result/artifact_digest',
          'artifact_summary_mismatch',
          'artifact result digest does not match the retained artifact digest',
        ),
      ],
    );
  } else if (
    envelope.evidence.kind === 'claim' &&
    envelope.evidence.result.claim_digest !== envelope.evidence.digest
  ) {
    throw new EvidenceEnvelopeError(
      'INVALID_BINDING',
      [
        issue(
          '/evidence/result/claim_digest',
          'claim_summary_mismatch',
          'claim result digest does not match the retained claim digest',
        ),
      ],
    );
  }
  return envelope;
}
